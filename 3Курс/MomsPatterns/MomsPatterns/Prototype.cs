//Паттерн прототип позволяет создавать новые объекты путём копирования уже существующих.
//Можно применять, для копирования игровых обектов с готовыми настройками

public abstract class Prototype
{
    //Уникальный индификатор прочитать снаружи можно, а изенить после создания нельзя
    public int Id { get; }

    protected Prototype(int id)
    {
        //Сохраняем индентификатор объекта при его создании
        Id = id;
    }

    public abstract Prototype Clone();
}